import type { GalleryImage } from "./types";

const list = (images: readonly GalleryImage[]) => (images.length ? images.map((img) => `- \`${img.url}\``) : ["None."]);

/**
 * `public/gallery/CREDITS.md`, written from the catalog by
 * `pnpm gallery:build`, so the credits cannot drift from the images.
 */
export function renderCredits(images: readonly GalleryImage[]): string {
  const own = images.filter((img) => img.source.kind === "own");
  const paper = images.filter((img) => img.source.kind === "paper");
  const cc0 = images.flatMap((img) => (img.source.kind === "cc0" ? [{ img, src: img.source }] : []));
  const lines = [
    "# Gallery credits",
    "",
    "Generated by `pnpm gallery:build` from `src/lib/gallery/catalog.ts`; do not edit by hand.",
    "",
    "Every image in this folder may be redistributed without conditions: it is",
    "either made for Ontab or released as CC0 by its author.",
    "",
    "## Made for Ontab",
    "",
    ...list(own),
    "",
    "## Drawn for Ontab with Paper Shaders",
    "",
    "Drawn with [Paper Shaders](https://github.com/paper-design/shaders) (Apache-2.0,",
    "© Lost Coast Labs) from the recipe of the same name in `scripts/gallery/shaders.json`.",
    "",
    ...list(paper),
    "",
    "## CC0",
    "",
  ];
  if (cc0.length) {
    lines.push("| Image | Author | Licence | Original | Retrieved |", "| --- | --- | --- | --- | --- |");
    for (const { img, src } of cc0) {
      lines.push(`| \`${img.url}\` | ${src.author} | ${src.license} | ${src.url} | ${src.retrieved} |`);
    }
  } else {
    lines.push("None.");
  }
  return lines.join("\n") + "\n";
}
